// Turns Foundry build output (contracts/out) into typed `as const` ABIs in src/generated.ts.
// Run via `npm run abis` from the repo root (it runs `forge build` first).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "../../../contracts/out");
const target = join(here, "../src/generated.ts");

/**
 * file: the .sol file name; name: the contract.
 * optional: skip quietly until a later ticket adds it.
 * bytecode / deployedBytecode: also export creation / runtime bytecode (for deploys and etching).
 */
const CONTRACTS = [
  { file: "IAave.sol", name: "IPool" },
  { file: "IAave.sol", name: "IPoolAddressesProvider" },
  { file: "IAave.sol", name: "IAaveOracle" },
  { file: "ISwapAdapter.sol", name: "ISwapAdapter" },
  { file: "IERC20Metadata.sol", name: "IERC20Metadata" },
  { file: "LiquidationShield.sol", name: "LiquidationShield", optional: true, bytecode: true },
  { file: "OracleSwapAdapter.sol", name: "OracleSwapAdapter", optional: true, bytecode: true },
  { file: "UniswapV3SwapAdapter.sol", name: "UniswapV3SwapAdapter", optional: true, bytecode: true },
  { file: "DemoPriceFeed.sol", name: "DemoPriceFeed", optional: true, bytecode: true, deployedBytecode: true },
];

const camel = (s) => s[0].toLowerCase() + s.slice(1);

if (!existsSync(outDir)) {
  console.error(`No Foundry output at ${outDir}. Run \`forge build\` in contracts/ first.`);
  process.exit(1);
}

const parts = [
  "// Generated by packages/shared/scripts/gen-abis.mjs from contracts/out. Do not edit by hand.",
  "// Regenerate with `npm run abis`.",
  "",
];
const written = [];
const skipped = [];

for (const c of CONTRACTS) {
  const path = join(outDir, c.file, `${c.name}.json`);
  if (!existsSync(path)) {
    if (c.optional) {
      skipped.push(c.name);
      continue;
    }
    console.error(`Missing artifact ${path}`);
    process.exit(1);
  }
  const artifact = JSON.parse(readFileSync(path, "utf8"));
  const id = camel(c.name);
  parts.push(`export const ${id}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;`, "");
  if (c.bytecode) parts.push(`export const ${id}Bytecode = "${artifact.bytecode.object}" as const;`, "");
  if (c.deployedBytecode) {
    parts.push(`export const ${id}DeployedBytecode = "${artifact.deployedBytecode.object}" as const;`, "");
  }
  written.push(c.name);
}

writeFileSync(target, parts.join("\n"));
console.log(`Wrote ${written.length} ABIs to ${target}: ${written.join(", ")}`);
if (skipped.length) console.log(`Not built yet (skipped): ${skipped.join(", ")}`);
